/**
 * SUTO OSNOVA — the monogram icon builder (task 155).
 * ONE geometry source for both favicon formats:
 *
 *   - renderMonogramSvg() — the VECTOR monogram (the "SO" monogram: a
 *     muted ring — the O — with a gold double-arc S inscribed, on the
 *     archival dark rounded square). Pure SVG shapes, no font, no
 *     external reference;
 *   - renderIco() — the classic favicon.ico: 16/32/48 PNG-embedded
 *     images rasterized from the SAME geometry (a small
 *     supersampled stamp rasterizer + a hand-rolled PNG encoder +
 *     the ICO container), so the vector and the bitmap can never
 *     drift apart;
 *   - renderMonogramRaster(size) — the raw RGBA buffer, exported so
 *     the gate can verify the BINARY palette compliance pixel by
 *     pixel.
 *
 * Colour discipline: every pixel is one of the Archival Iron palette
 * values (or fully transparent corners) — verified by the gate.
 * Deterministic: no clocks, no RNG — the same bytes every run.
 * Run directly to (re)generate client/public/favicon.svg + .ico:
 *   node scripts/monogramIcon.mjs
 */
import { deflateSync } from 'node:zlib';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

/** The monogram geometry, in a 32-unit viewBox. */
export const MONOGRAM = Object.freeze({
  viewBox: 32,
  cornerRadius: 6,
  ring: Object.freeze({ cx: 16, cy: 16, r: 9.5, halfWidth: 1.15 }),
  // The S centreline: two stacked bowls over a middle sweep.
  sPath: 'M20.5 11.5 C20.5 8.5 11.5 8.5 11.5 12.5 '
    + 'C11.5 15.5 20.5 16.5 20.5 20.5 C20.5 23.5 11.5 23.5 11.5 20.5',
  sStrokes: Object.freeze([
    // Cubic segments as [p0, c1, c2, p1] for the rasterizer.
    [[20.5, 11.5], [20.5, 8.5], [11.5, 8.5], [11.5, 12.5]],
    [[11.5, 12.5], [11.5, 15.5], [20.5, 16.5], [20.5, 20.5]],
    [[20.5, 20.5], [20.5, 23.5], [11.5, 23.5], [11.5, 20.5]],
  ]),
  sHalfWidth: 1.3,
  colors: Object.freeze({
    bg: '#101114', ring: '#96A2A8', mark: '#D4A853',
  }),
  icoSizes: Object.freeze([16, 32, 48]),
});

const { viewBox, cornerRadius, ring, sStrokes, sHalfWidth, colors, icoSizes } = MONOGRAM;

/** The vector monogram (the single source svg). */
export function renderMonogramSvg() {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${viewBox} ${viewBox}" role="img" aria-label="SUTO OSNOVA monogram">
  <!-- Generated by scripts/monogramIcon.mjs — edit the GEOMETRY there. -->
  <rect width="${viewBox}" height="${viewBox}" rx="${cornerRadius}" fill="${colors.bg}"/>
  <circle cx="${ring.cx}" cy="${ring.cy}" r="${ring.r}" fill="none" stroke="${colors.ring}" stroke-width="${ring.halfWidth * 2}"/>
  <path d="${MONOGRAM.sPath}" fill="none" stroke="${colors.mark}" stroke-width="${sHalfWidth * 2}" stroke-linecap="round"/>
</svg>
`;
}

/** Cubic bezier point at t (per axis). */
function cubicAt(p0, c1, c2, p1, t) {
  const u = 1 - t;
  return (u * u * u * p0) + (3 * u * u * t * c1) + (3 * u * t * t * c2) + (t * t * t * p1);
}

/** The S centreline samples (48 per segment). */
function sSamples() {
  const points = [];
  for (const [p0, c1, c2, p1] of sStrokes) {
    for (let i = 0; i <= 48; i += 1) {
      const t = i / 48;
      points.push([
        cubicAt(p0[0], c1[0], c2[0], p1[0], t),
        cubicAt(p0[1], c1[1], c2[1], p1[1], t),
      ]);
    }
  }
  return points;
}

/** Inside the rounded square (shape space 0..32)? */
function insideGround(x, y) {
  const inside = x >= 0 && x < viewBox && y >= 0 && y < viewBox;
  if (!inside) return false;
  const cx = Math.min(Math.max(x, cornerRadius), viewBox - cornerRadius);
  const cy = Math.min(Math.max(y, cornerRadius), viewBox - cornerRadius);
  return (x - cx) ** 2 + (y - cy) ** 2 <= cornerRadius ** 2;
}

/** Rasterize the monogram: an RGBA buffer (row-major, 4 bytes/px). */
export function renderMonogramRaster(size) {
  const scale = size / viewBox;
  const samples = sSamples();
  const buffer = Buffer.alloc(size * size * 4);
  const SUB = 4; // 4x4 supersampling per pixel
  const palette = [colors.bg, colors.ring, colors.mark]
    .map((hex) => [parseInt(hex.slice(1, 3), 16), parseInt(hex.slice(3, 5), 16), parseInt(hex.slice(5, 7), 16)]);

  for (let py = 0; py < size; py += 1) {
    for (let px = 0; px < size; px += 1) {
      let covered = 0;
      let [r, g, b, a] = [0, 0, 0, 0];
      for (let sy = 0; sy < SUB; sy += 1) {
        for (let sx = 0; sx < SUB; sx += 1) {
          const x = (px + (sx + 0.5) / SUB) / scale;
          const y = (py + (sy + 0.5) / SUB) / scale;
          if (!insideGround(x, y)) continue;
          covered += 1;
          let colour = colors.bg;
          const ringDistance = Math.abs(Math.hypot(x - ring.cx, y - ring.cy) - ring.r);
          if (ringDistance <= ring.halfWidth) colour = colors.ring;
          for (const [qx, qy] of samples) {
            if ((x - qx) ** 2 + (y - qy) ** 2 <= sHalfWidth ** 2) {
              colour = colors.mark;
              break;
            }
          }
          r += parseInt(colour.slice(1, 3), 16);
          g += parseInt(colour.slice(3, 5), 16);
          b += parseInt(colour.slice(5, 7), 16);
        }
      }
      if (covered === 0) continue; // transparent corner
      // QUANTIZE to the nearest palette colour (task 155): thin strokes
      // at 16px would otherwise blend into non-palette values — every
      // opaque pixel stays EXACTLY a palette value (crisp small sizes,
      // palette-compliant bytes), the silhouette softens via alpha.
      const avg = [Math.round(r / covered), Math.round(g / covered), Math.round(b / covered)];
      const nearest = palette
        .map((entry) => ({ entry, distance: (entry[0] - avg[0]) ** 2 + (entry[1] - avg[1]) ** 2 + (entry[2] - avg[2]) ** 2 }))
        .sort((a, b) => a.distance - b.distance)[0].entry;
      const offset = (py * size + px) * 4;
      buffer[offset] = nearest[0];
      buffer[offset + 1] = nearest[1];
      buffer[offset + 2] = nearest[2];
      buffer[offset + 3] = Math.round((covered / (SUB * SUB)) * 255);
    }
  }
  return buffer;
}

/** CRC-32 (PNG chunk checksums). */
function crc32(buffer) {
  let crc = 0xFFFFFFFF;
  for (const byte of buffer) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit += 1) {
      crc = (crc >>> 1) ^ (0xEDB88320 & -(crc & 1));
    }
  }
  return (crc ^ 0xFFFFFFFF) >>> 0;
}

/** One PNG chunk: length, type, data, CRC(type+data). */
function pngChunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'latin1'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([length, body, crc]);
}

/** Encode an RGBA buffer as a PNG (8-bit, colour type 6). */
export function encodePng(width, height, rgba) {
  const signature = Buffer.from([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A]);
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // colour type: RGBA
  const stride = width * 4;
  const scanlines = Buffer.alloc(height * (stride + 1));
  for (let row = 0; row < height; row += 1) {
    scanlines[row * (stride + 1)] = 0; // filter: none
    rgba.copy(scanlines, row * (stride + 1) + 1, row * stride, (row + 1) * stride);
  }
  return Buffer.concat([
    signature,
    pngChunk('IHDR', ihdr),
    pngChunk('IDAT', deflateSync(scanlines)),
    pngChunk('IEND', Buffer.alloc(0)),
  ]);
}

/** The favicon.ico container: PNG-embedded images at 16/32/48. */
export function renderIco() {
  const images = icoSizes.map((size) => ({
    size,
    png: encodePng(size, size, renderMonogramRaster(size)),
  }));
  const header = Buffer.alloc(6 + images.length * 16);
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(({ size, png }, index) => {
    const entry = 6 + index * 16;
    header[entry] = size >= 256 ? 0 : size;
    header[entry + 1] = size >= 256 ? 0 : size;
    header.writeUInt16LE(1, entry + 4); // colour planes
    header.writeUInt16LE(32, entry + 6); // bits per pixel
    header.writeUInt32LE(png.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += png.length;
  });
  return Buffer.concat([header, ...images.map((image) => image.png)]);
}

/** CLI: regenerate both favicon files. */
const isCli = process.argv[1]
  && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
if (isCli) {
  const publicDir = fileURLToPath(new URL('../client/public/', import.meta.url));
  writeFileSync(path.join(publicDir, 'favicon.svg'), renderMonogramSvg());
  writeFileSync(path.join(publicDir, 'favicon.ico'), renderIco());
  process.stdout.write('favicon.svg + favicon.ico regenerated\n');
}
